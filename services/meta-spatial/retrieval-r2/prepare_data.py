#!/usr/bin/env python3
"""Bounded public ABO acquisition. No private directories, credentials or APIs.

Metadata, image bytes, grouping, split assignments and dropped records are
receipted. A second catalog photograph is the query; the main photograph is
the gallery. Text hints are explicitly generated from published attributes,
not OCR observations. No source image/caption is generated by this script.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import io
import json
import re
import threading
import time
import urllib.error
import urllib.parse
import urllib.request
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

BASE = "https://amazon-berkeley-objects.s3.amazonaws.com/"
PARTITIONS = ("train", "dev", "cal", "test", "ood")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def stable(value: str) -> str:
    return sha256(value.encode("utf-8"))


def canonical(value) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


class UnionFind:
    def __init__(self, items):
        self.parents = {item: item for item in items}

    def find(self, item):
        while self.parents[item] != item:
            self.parents[item] = self.parents[self.parents[item]]
            item = self.parents[item]
        return item

    def join(self, a, b):
        a, b = self.find(a), self.find(b)
        if a != b:
            self.parents[max(a, b)] = min(a, b)


def values(record, key, english=True):
    result = []
    for item in record.get(key, []) or []:
        if not isinstance(item, dict) or not isinstance(item.get("value"), str):
            continue
        if english and item.get("language_tag") not in (None, "en_US", "en_GB"):
            continue
        value = item["value"].strip()
        if value and value not in result:
            result.append(value)
    return result


def normalize(text):
    return " ".join(re.findall(r"\w+", text.casefold(), flags=re.UNICODE))


def family_keys(record):
    """Conservative reproducible family candidates; never infer identity proof."""
    keys = ["image:" + i for i in record["image_ids"]]
    brand = normalize(record.get("brand", ""))
    category = record["category"]
    for model in record.get("model_numbers", []):
        model = normalize(model)
        if len(model) >= 5 and model not in {"not applicable", "one size", "unknown"}:
            keys.append("model:" + brand + ":" + model)
    # Remove published variant attributes from the title, plus numeric sizes.
    title = normalize(record["title"])
    for attr in sorted(record.get("variant_attributes", []), key=len, reverse=True):
        normalized = normalize(attr)
        if normalized:
            title = (" " + title + " ").replace(" " + normalized + " ", " ").strip()
    title = " ".join(t for t in title.split() if not any(c.isdigit() for c in t))
    if len(title.split()) >= 4:
        keys.append("title:" + category + ":" + brand + ":" + title)
    return keys


def group_records(records, include_bytes=False):
    uf = UnionFind(r["product_id"] for r in records)
    seen = {}
    for r in sorted(records, key=lambda r: r["product_id"]):
        keys = family_keys(r)
        if include_bytes:
            keys += ["bytes:" + v["sha256"] for v in r["views"]]
            keys += ["prior_family:" + r["family_id"]]
        for key in keys:
            if key in seen:
                uf.join(r["product_id"], seen[key])
            else:
                seen[key] = r["product_id"]
    components = defaultdict(list)
    for r in records:
        components[uf.find(r["product_id"])].append(r)
    for component in components.values():
        family_id = stable("ABO-family-v1\n" + "\n".join(sorted(r["product_id"] for r in component)))
        for r in component:
            r["family_id"] = family_id
    return components


def split_for(family_id, categories, ood_categories):
    if set(categories) & set(ood_categories):
        return "ood"
    bucket = int(stable("ABO-split-v1:" + family_id)[:16], 16) % 10000
    if bucket < 6000:
        return "train"
    if bucket < 7500:
        return "dev"
    if bucket < 8750:
        return "cal"
    return "test"


class Downloader:
    def __init__(self, root, max_bytes, deadline):
        self.root, self.max_bytes, self.deadline = root, max_bytes, deadline
        self.total_bytes = 0
        self.receipts = []
        self.lock = threading.Lock()
        self.path_locks = {}
        self.completed = set()
        self.reserved = 0

    def get(self, key, max_file_bytes):
        with self.lock:
            path_lock = self.path_locks.setdefault(key, threading.Lock())
        with path_lock:
            return self._get_locked(key, max_file_bytes)

    def _get_locked(self, key, max_file_bytes):
        if time.monotonic() > self.deadline:
            raise RuntimeError("preparation_deadline_exceeded")
        parts = Path(key).parts
        if key.startswith("/") or ".." in parts or "\\" in key:
            raise ValueError("invalid_source_path")
        url = BASE + urllib.parse.quote(key, safe="/")
        path = self.root / "source" / key
        if key in self.completed:
            return path.read_bytes(), path
        if path.exists():
            data = path.read_bytes()
            headers = {}
            cached = True
            with self.lock:
                if self.total_bytes + self.reserved + len(data) > self.max_bytes:
                    raise RuntimeError("download_byte_budget_exceeded")
                self.total_bytes += len(data)
        else:
            request = urllib.request.Request(url, headers={"User-Agent": "MetaLensRetrievalResearch/2"})
            with urllib.request.urlopen(request, timeout=30) as response:
                headers = {k.lower(): v for k, v in response.headers.items() if k.lower() in {"etag", "last-modified", "content-length"}}
                declared = int(headers.get("content-length", 0))
                if declared > max_file_bytes:
                    raise RuntimeError("download_byte_budget_exceeded")
                chunks = []
                length = 0
                while True:
                    amount = min(65536, max_file_bytes + 1 - length)
                    with self.lock:
                        if self.total_bytes + self.reserved + amount > self.max_bytes:
                            raise RuntimeError("download_byte_budget_exceeded")
                        self.reserved += amount
                    block = b""
                    try:
                        block = response.read(amount)
                    finally:
                        with self.lock:
                            self.reserved -= amount
                            self.total_bytes += len(block)
                    if not block:
                        break
                    chunks.append(block)
                    length += len(block)
                    if length > max_file_bytes:
                        raise RuntimeError("download_byte_budget_exceeded")
                    if time.monotonic() > self.deadline:
                        raise RuntimeError("preparation_deadline_exceeded")
                data = b"".join(chunks)
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_name(path.name + ".part")
            temporary.write_bytes(data)
            temporary.replace(path)
            cached = False
        if len(data) > max_file_bytes:
            raise RuntimeError("download_byte_budget_exceeded")
        with self.lock:
            self.receipts.append({"url": url, "path": str(path.relative_to(self.root)), "sha256": sha256(data), "bytes": len(data), "headers": headers, "cache_reused": cached})
            self.completed.add(key)
        return data, path


def parse_record(raw):
    titles = values(raw, "item_name")
    ids = [raw.get("main_image_id")] + (raw.get("other_image_id") or [])
    ids = list(dict.fromkeys(i for i in ids if isinstance(i, str) and i))
    if not titles or len(ids) < 2 or not isinstance(raw.get("item_id"), str):
        return None
    category = (values(raw, "product_type") or ["UNKNOWN"])[0]
    if category == "UNKNOWN":
        return None
    brand = (values(raw, "brand") or [""])[0]
    attributes = {key: values(raw, key) for key in ("color", "material", "style", "pattern", "size", "item_shape")}
    multilingual = {}
    for item in raw.get("item_name", []):
        if isinstance(item, dict) and isinstance(item.get("value"), str):
            language = item.get("language_tag", "und")
            multilingual.setdefault(language, item["value"])
    hint = " ".join([category.replace("_", " ").lower()] + attributes["color"][:1] + attributes["material"][:1])
    return {"product_id": raw["item_id"], "title": titles[0], "titles": multilingual, "category": category, "brand": brand, "model_numbers": values(raw, "model_number"), "variant_attributes": attributes["color"] + attributes["size"] + attributes["pattern"], "image_ids": ids, "attributes": attributes, "text_hint": hint, "text_hint_provenance": "deterministic_published_attributes_not_ocr", "metadata_text": " | ".join(titles[:1] + [category, brand] + [v for a in attributes.values() for v in a])}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--output", required=True, type=Path)
    p.add_argument("--max-products", type=int, default=6000)
    p.add_argument("--max-download-bytes", type=int, default=3000000000)
    p.add_argument("--max-seconds", type=int, default=1800)
    p.add_argument("--shards", type=int, default=16)
    p.add_argument("--workers", type=int, default=12)
    args = p.parse_args()
    if not 200 <= args.max_products <= 20000 or not 1 <= args.shards <= 16 or not 1 <= args.workers <= 16 or not 1 <= args.max_download_bytes <= 3000000000 or not 60 <= args.max_seconds <= 7200:
        p.error("bounded limits required")
    if (args.output / "dataset.json").exists():
        p.error("output already has a sealed dataset; choose a fresh output")
    args.output.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    d = Downloader(args.output, args.max_download_bytes, started + args.max_seconds)
    licensing, _ = d.get("LICENSE-CC-BY-4.0.txt", 1048576)
    records_by_id = {}
    for shard in range(args.shards):
        data, _ = d.get(f"listings/metadata/listings_{shard:x}.json.gz", 64000000)
        for line in gzip.decompress(data).splitlines():
            r = parse_record(json.loads(line))
            if r is not None:
                previous = records_by_id.get(r["product_id"])
                if previous:
                    previous["image_ids"] = list(dict.fromkeys(previous["image_ids"] + r["image_ids"]))
                    previous["titles"].update(r["titles"])
                else:
                    records_by_id[r["product_id"]] = r
        print(json.dumps({"stage": "metadata", "shard": shard, "eligible_products": len(records_by_id), "bytes": d.total_bytes}), flush=True)
    image_data, _ = d.get("images/metadata/images.csv.gz", 64000000)
    image_map = {r["image_id"]: r for r in csv.DictReader(io.StringIO(gzip.decompress(image_data).decode("utf-8")))}
    records = list(records_by_id.values())
    components = group_records(records)
    eligible = [c for c in components.values() if len(c) <= 50 and any(sum(i in image_map for i in r["image_ids"]) >= 2 for r in c)]
    counts = Counter(c[0]["category"] for c in eligible)
    categories = sorted((c for c, n in counts.items() if n >= 20), key=lambda c: stable("ABO-ood-v1:" + c))
    if len(categories) < 5:
        raise RuntimeError("insufficient_categories_for_disjoint_ood")
    ood_categories = categories[:max(1, len(categories) // 8)]
    # Deterministic category-round-robin keeps low-frequency household groups represented.
    queues = defaultdict(list)
    for component in sorted(eligible, key=lambda c: stable("select:" + c[0]["family_id"])):
        queues[component[0]["category"]].append(component)
    selected = []
    while queues and len(selected) < args.max_products:
        for category in sorted(list(queues), key=lambda c: stable("category:" + c)):
            component = queues[category].pop(0)
            if len(selected) + len(component) <= args.max_products:
                selected.extend(component)
            if not queues[category]:
                del queues[category]
            if len(selected) >= args.max_products:
                break
    from PIL import Image
    successes, drops, downloaded = [], [], {}
    cache_lock = threading.Lock()

    def acquire_product(r):
        views = []
        failures = []
        for image_id in r["image_ids"]:
            if image_id not in image_map:
                continue
            try:
                key = "images/small/" + image_map[image_id]["path"]
                with cache_lock:
                    cached_view = downloaded.get(key)
                if cached_view is not None:
                    view = dict(cached_view)
                else:
                    data, path = d.get(key, 8388608)
                    with Image.open(io.BytesIO(data)) as im:
                        im.load()
                        width, height = im.size
                        if min(width, height) < 32 or max(width, height) > 4096:
                            raise ValueError("unsupported_image_dimensions")
                    view = {"image_id": image_id, "path": str(path.relative_to(args.output)), "sha256": sha256(data), "width": width, "height": height}
                    with cache_lock:
                        downloaded[key] = view
                if view["sha256"] not in {v["sha256"] for v in views}:
                    views.append(view)
                if len(views) == 2:
                    break
            except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError, ValueError) as exc:
                failures.append({"product_id": r["product_id"], "image_id": image_id, "reason": type(exc).__name__})
        if len(views) == 2:
            r["views"] = views
            return r, failures
        else:
            failures.append({"product_id": r["product_id"], "reason": "no_two_distinct_valid_photographs"})
            return None, failures

    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        for index, (record, failures) in enumerate(pool.map(acquire_product, selected)):
            drops.extend(failures)
            if record is not None:
                successes.append(record)
            if index % 100 == 0:
                print(json.dumps({"stage": "images", "processed": index + 1, "complete_products": len(successes), "bytes": d.total_bytes}), flush=True)
    components = group_records(successes, include_bytes=True)
    for component in components.values():
        split = split_for(component[0]["family_id"], [r["category"] for r in component], ood_categories)
        for r in component:
            r["split"] = split
    split_counts = Counter(r["split"] for r in successes)
    if any(split_counts[s] < 20 for s in PARTITIONS):
        raise RuntimeError("insufficient_partition_size:" + json.dumps(split_counts))
    manifest = {"schema_version": 1, "kind": "meta.public-abo-retrieval", "license": "CC-BY-4.0", "attribution": "Amazon.com; ABO dataset by Collins et al., CVPR 2022", "license_sha256": sha256(licensing), "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "split_policy": "family_components_v1; 60/15/12.5/12.5; whole-category OOD; exact image-byte duplicates merged before assignment", "split_limitations": ["heuristic family grouping cannot prove all visually identical variants grouped", "catalog photographs are not wearable-camera field data"], "ood_categories": ood_categories, "counts": dict(split_counts), "family_counts": dict(Counter(c[0]["split"] for c in components.values())), "download_bytes": d.total_bytes, "preparation_seconds": time.monotonic() - started, "sources": sorted(d.receipts, key=lambda r: r["path"]), "drops": drops, "records": sorted(successes, key=lambda r: r["product_id"])}
    payload = canonical(manifest)
    (args.output / "dataset.json").write_bytes(payload)
    (args.output / "dataset.sha256").write_text(sha256(payload) + "\n")
    print(json.dumps({"stage": "SEALED", "dataset_sha256": sha256(payload), "counts": dict(split_counts), "bytes": d.total_bytes}), flush=True)


if __name__ == "__main__":
    main()
