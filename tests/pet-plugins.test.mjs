import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir,mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildAll,buildPlugin} from '../scripts/build-pet-plugins.mjs';

const ROOT=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const pluginRoot=resolve(ROOT,'plugins');
const readJson=async p=>JSON.parse(await readFile(p,'utf8'));
const petNames=async()=>((await readdir(resolve(ROOT,'pets'),{withFileTypes:true})).filter(e=>e.isDirectory()).map(e=>e.name).sort());

test('all 34 plugin source packages are exact deterministic generated bytes',async()=>{
  const generated=await buildAll({root:ROOT,output:pluginRoot,check:true});
  assert.equal(generated.length,34);
  assert.equal(generated.reduce((n,p)=>n+p.files.length,0),102);
  assert.deepEqual(generated.map(p=>p.name), (await petNames()).map(p=>`junction-${p}`));
});

test('portable plugin manifests contain one self-contained skill, no fake host or privileged MCP',async()=>{
  const names=await petNames();
  const seen=new Set();
  for(const company of names){
    const base=join(pluginRoot,`junction-${company}`);
    const pet=await readJson(join(ROOT,'pets',company,'pet.json'));
    const manifest=await readJson(join(base,'plugin.json'));
    const provenance=await readJson(join(base,'assets','source-manifest.json'));
    const skill=await readFile(join(base,'skills',provenance.skillName,'SKILL.md'),'utf8');
    assert.equal(manifest.$schema,'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json');
    assert.equal(manifest.name,pet.slug);
    assert.match(manifest.name,/^[a-z0-9]+(?:-[a-z0-9]+)*$/);
    assert.ok(manifest.name.length<=64);
    assert.match(manifest.version,/^\d+\.\d+\.\d+$/);
    assert.equal(manifest.author.name,'Sales Squad Oy');
    assert.equal(manifest.extensions['com.openai'].interface.capabilities.length,0);
    assert.ok(manifest.extensions['com.openai'].interface.shortDescription.length<=30);
    assert.equal(manifest.extensions['com.openai'].interface.defaultPrompt,pet.starterPrompts[0]);
    assert.ok(!('mcpServers' in manifest));
    assert.ok(!('apps' in manifest.extensions['com.openai']));
    assert.equal(provenance.petId,pet.id);
    assert.equal(provenance.source.commit,null);
    assert.equal(provenance.source.commitVerified,false);
    assert.deepEqual(provenance.status,{packageGenerated:true,pluginInstalled:false,mcpConnected:false,liveAgentRunVerified:false});
    assert.match(skill,new RegExp(`^---\\nname: ${provenance.skillName}\\ndescription: `));
    assert.ok(skill.includes(await readFile(join(ROOT,'pets',company,'AGENTS.md'),'utf8').then(s=>s.trim())));
    assert.ok(skill.includes('independently')||skill.includes('independent'));
    assert.ok(skill.includes('source-bound receipts'));
    assert.ok(!/sk-[A-Za-z0-9_-]{24}|ghp_[A-Za-z0-9]{24}|Bearer\s+[A-Za-z0-9_-]{20}/.test(skill));
    assert.deepEqual((await readdir(base)).sort(),['assets','plugin.json','skills']);
    if(seen.has(manifest.name))throw Error('duplicate plugin '+manifest.name);
    seen.add(manifest.name);
  }
});

test('generator rejects malformed company identity, version and fake endorsement',async()=>{
  const pet=await readJson(join(ROOT,'pets','mariadb','pet.json'));
  const source={AGENTS:'Independent instructions'};
  const wrong=structuredClone(pet);wrong.slug='other';
  assert.throws(()=>buildPlugin(wrong,source),/identity/);
  const version=structuredClone(pet);version.version='latest';
  assert.throws(()=>buildPlugin(version,source),/SemVer/);
  const official=structuredClone(pet);official.availability.companyEndorsed=true;
  assert.throws(()=>buildPlugin(official,source),/endorsement/);
});

test('drifted package is refused by deterministic verification',async()=>{
  const folder=await mkdtemp(join(tmpdir(),'junction-plugin-test-'));
  try{
    await buildAll({root:ROOT,output:folder,check:false});
    await writeFile(join(folder,'junction-mariadb','plugin.json'),'{}\n');
    await assert.rejects(buildAll({root:ROOT,output:folder,check:true}),/drift/);
  }finally{await rm(folder,{recursive:true,force:true});}
});
