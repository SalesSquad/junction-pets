// Measures the claim check on this product's own sentences: how many true sentences it
// passes, and how many deliberately corrupted ones it stops. Real service calls.
// Usage: TYPESAFE_API_KEY=... node src/eval-claim-check.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { buildApp } from './build.mjs';
import { buildBrief } from './claims.mjs';
import { judgeClaim } from './claim-check.mjs';

const SWAPS = [['above', 'below'], ['more', 'fewer'], ['worse', 'better']];
export const CORRUPTIONS = {
  direction(text) {
    for (const [a, b] of SWAPS) {
      const ra = new RegExp(`\\b${a}\\b`); const rb = new RegExp(`\\b${b}\\b`);
      if (ra.test(text)) return text.replace(ra, b);
      if (rb.test(text)) return text.replace(rb, a);
    }
    return null;
  },
  number(text) {
    const m = [...text.matchAll(/\d+\.\d+|\d+/g)].find((x) => !/^(19|20)\d\d$/.test(x[0]) && Number(x[0]) > 3 && Number(x[0]) !== 80 && Number(x[0]) !== 95);
    if (!m) return null;
    const decimals = (m[0].split('.')[1] || '').length;
    return text.slice(0, m.index) + (Number(m[0]) * 1.5).toFixed(decimals) + text.slice(m.index + m[0].length);
  },
  place(text, { regionName, otherName }) { return text.includes(regionName) ? text.replace(regionName, otherName) : null; },
  causal(text, { kind }) {
    if (kind === 'SCENARIO') {
      if (text.includes('Under the stated assumptions this postpones about')) return text.replace('Under the stated assumptions this postpones about', 'This will certainly prevent');
      if (text.includes('is expected to add')) return text.replace('is expected to add', 'is guaranteed to add');
      return null;
    }
    return `${text} This proves that poor care in the county is the cause.`;
  },
};

async function pool(items, n, fn) {
  const out = new Array(items.length); let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { for (;;) { const k = i; i += 1; if (k >= items.length) return; out[k] = await fn(items[k]); } }));
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const apiKey = process.env.TYPESAFE_API_KEY;
  if (!apiKey) { console.log(JSON.stringify({ status: 'NOT_CONFIGURED' })); process.exit(0); }
  const app = buildApp();
  const names = app.analysis.regions.map((r) => r.name);
  const cases = [];
  app.analysis.regions.forEach((region, idx) => {
    const ctx = { regionName: region.name, otherName: names[(idx + 7) % names.length] };
    for (const claim of buildBrief(app, region.regionId).claims) {
      cases.push({ id: claim.id, variant: 'true', claim });
      for (const [variant, fn] of Object.entries(CORRUPTIONS)) {
        const text = fn(claim.text, { ...ctx, kind: claim.kind });
        if (text && text !== claim.text) cases.push({ id: claim.id, variant, claim: { ...claim, text } });
      }
    }
  });
  const usage = { input_tokens: 0, output_tokens: 0 }; let model = null; let errors = 0;
  const judged = await pool(cases, 8, async (c) => {
    try {
      const r = await judgeClaim(c.claim, app.evidence, { apiKey });
      usage.input_tokens += r.usage?.input_tokens ?? 0; usage.output_tokens += r.usage?.output_tokens ?? 0; model = r.model ?? model;
      return { id: c.id, variant: c.variant, text: c.claim.text, verdict: r.verdict, probability: r.probability, overclaim: r.overclaim };
    } catch { errors += 1; return { id: c.id, variant: c.variant, text: c.claim.text, verdict: 'ERROR' }; }
  });
  const summary = {};
  for (const j of judged.filter((x) => x.verdict !== 'ERROR')) {
    const s = (summary[j.variant] ||= { n: 0, SUPPORTED: 0, UNCLEAR: 0, NOT_SUPPORTED: 0 });
    s.n += 1; s[j.verdict] += 1;
  }
  for (const [variant, s] of Object.entries(summary)) {
    if (variant === 'true') s.passRate = Math.round((s.SUPPORTED / s.n) * 1000) / 1000;
    else s.stoppedRate = Math.round(((s.n - s.SUPPORTED) / s.n) * 1000) / 1000; // not auto-accepted
  }
  const corrupted = judged.filter((x) => x.variant !== 'true' && x.verdict !== 'ERROR');
  const out = {
    schemaVersion: 'care-equity-claim-check-eval-v1', ranAt: new Date().toISOString(), snapshotSha256: app.provenance.snapshotSha256, service: 'TypeSafe System One', model,
    autoAccept: 0.8, cases: judged.length, errors, usage, summary,
    overall: {
      trueSentencesPassed: summary.true?.passRate ?? null,
      corruptedSentencesStopped: corrupted.length ? Math.round((corrupted.filter((x) => x.verdict !== 'SUPPORTED').length / corrupted.length) * 1000) / 1000 : null,
    },
    falseAccepts: corrupted.filter((x) => x.verdict === 'SUPPORTED').slice(0, 25),
    trueNotPassed: judged.filter((x) => x.variant === 'true' && x.verdict !== 'SUPPORTED' && x.verdict !== 'ERROR').slice(0, 25),
    verdicts: Object.fromEntries(judged.filter((x) => x.variant === 'true').map((x) => [x.id, { verdict: x.verdict, probability: x.probability, overclaim: x.overclaim }])),
    note: 'Corruptions are generated by code from the true sentences: flipped direction, a number multiplied by 1.5, another county name, and an added causal or certainty claim. A corrupted sentence counts as stopped when it is not auto-accepted (it goes to a human or is rejected).',
  };
  mkdirSync(new URL('../data/claim-check/', import.meta.url), { recursive: true });
  writeFileSync(new URL('../data/claim-check/eval-v1.json', import.meta.url), `${JSON.stringify(out, null, 1)}\n`);
  console.log(JSON.stringify({ model, cases: out.cases, errors, usage, summary, overall: out.overall }));
}
