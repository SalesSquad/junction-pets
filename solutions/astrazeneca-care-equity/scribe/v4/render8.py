"""Render scribe/v4/RESULTS.md from data/scribe/v4/eval/results-v1.json. Every number is read from the results dict;
nothing is typed by hand. SYNTHETIC notes only; a person confirms every extracted event."""

from __future__ import annotations

ORDER = ("A", "A'", "B", "C", "v2data", "nemotron")
NAMES = {"A": "A (270M absolute + rule A)", "A'": "A' (270M absolute + rule A')", "B": "B (270M expression)",
         "C": "C (1B expression)", "v2data": "C-270m-all-v2data + rule A' (earlier product adapter)", "nemotron": "Nemotron reader v3"}


def pct(x):
    if not x or x.get("value") is None:
        return "n/a"
    return f"{x['k']}/{x['n']} ({100 * x['value']:.1f}%, {100 * x['ci95'][0]:.1f}-{100 * x['ci95'][1]:.1f})"


def short(x):
    if not x or x.get("value") is None:
        return "n/a"
    return f"{x['k']}/{x['n']} ({100 * x['value']:.1f}%)"


def sysd(doc, split, s):
    return doc["sets"][split]["systems"].get(s)


def cmp_line(c):
    return (f"{NAMES.get(c['a'], c['a'])} {c['a_correct']}/{c['n']} vs {NAMES.get(c['b'], c['b'])} {c['b_correct']}/{c['n']}: "
            f"{c['difference_b_minus_a_points']:+.1f} points for the second; {c['a_only_correct']} notes only the first got right, "
            f"{c['b_only_correct']} only the second; exact McNemar p {P(c['exact_mcnemar_p'])}")


def P(p):
    """Exact McNemar p for the page: below 1e-6 it is shown as < 1e-6, otherwise = p to 3 significant digits."""
    return "< 1e-6" if p < 1e-6 else f"= {p:.3g}"


def render(doc):
    L = []
    a = L.append
    a("# Step 8: preregistered evaluation and cascade recalibration")
    a("")
    a(f"Generated by `scribe/v4/eval8.py score` at {doc['created_utc']} from `data/scribe/v4/eval/results-v1.json`; every number below is read from that file. "
      "All notes are SYNTHETIC. Nothing here is a clinical claim. Every extracted event is a proposal: it is pre-filled for one-click confirmation "
      "or it needs editing, and a person confirms every event.")
    a("")
    # headline
    a("## Headline")
    a("")
    pr = doc.get("primary_result")
    st = doc["sets"]["stress"]["systems"]
    if pr:
        a(f"- **Primary result (stress set, held-out phrasings, preregistered): {pr['headline']}.** "
          f"B got {pr['b_correct']}/{pr['n']} notes exactly right and A' got {pr['a_correct']}/{pr['n']} "
          f"({pr['difference_b_minus_a_points']:+.1f} points for B; exact McNemar p {P(pr['exact_mcnemar_p'])}). "
          f"On the standard slice B got {pct(pr['B_standard_slice'])}. The criterion was: {pr['criterion']}. Met: {'yes' if pr['met'] else 'no'}.")
        if pr["A_prime_wins"]:
            a("- **The rule A' beats the learned reader on the held-out phrasings.**")
        else:
            a("- The rule A' does not beat the learned reader B on the held-out phrasings. The frozen lexicon was written to exclude these phrasings "
              "(number words 7-12 and 'toissapäivänä'), so A' cannot date them; the comparison tests whether B generalises beyond its training phrasings.")
    std = next((c for c in doc["comparisons"].get("stress_standard") or [] if c["a"] == "A'" and c["b"] == "B"), None)
    tst = next((c for c in doc["comparisons"].get("test") or [] if c["a"] == "A'" and c["b"] == "B"), None)
    if std and tst:
        a(f"- Plain answer on the other phrasings: on the stress standard slice the rule A' and B are level "
          f"({std['a_correct']}/{std['n']} against {std['b_correct']}/{std['n']}, p {P(std['exact_mcnemar_p'])}); on the 700 test notes "
          f"(post hoc) A' is {'ahead' if tst['a_correct'] > tst['b_correct'] else 'behind' if tst['a_correct'] < tst['b_correct'] else 'level'} "
          f"({tst['a_correct']} against {tst['b_correct']}, p {P(tst['exact_mcnemar_p'])}). So on the familiar test phrasings the careful rule "
          f"{'beats' if tst['a_correct'] > tst['b_correct'] and tst['exact_mcnemar_p'] < 0.05 else 'does not beat'} the learned 270M reader"
          + ("; where it is new, neither 270M system gets even half of the notes right." if st["A'"]["slices"]["heldout"]["value"] < 0.5 and st["B"]["slices"]["heldout"]["value"] < 0.5 else "."))
    for c in doc["comparisons"].get("stress_heldout") or []:
        if c["a"] == "A'" and c["b"] in ("C", "nemotron"):
            a(f"- Descriptive, not preregistered: on the same held-out slice, {cmp_line(c)}.")
    for s in ("A'", "B", "C", "nemotron"):
        if s in st:
            x = st[s]
            a(f"- {NAMES[s]}: stress {short(x['exact_match'])}; held-out slice {short(x['slices']['heldout'])}; "
              f"standard slice {short(x['slices']['standard'])}; vague facts sent to a person {short(x['vague_outcome']['sent_to_person'])}, "
              f"precise date invented {short(x['vague_outcome']['invented_precise_date'])}.")
    cas = doc.get("cascade")
    if cas and cas.get("chosen"):
        ch = next(c for c in cas["configurations"] if c["gemma"] == cas["chosen"]["gemma"] and c["signal"] == cas["chosen"]["signal"])
        t = ch["test"]
        b = cas["baseline_today"]
        a(f"- **Cascade (thresholds set on validation only):** with Gemma {ch['gemma']} and signal '{ch['signal']}', "
          f"{t['prefilled_for_one_click_confirmation']['k']}/{t['notes']} test notes are pre-filled for one-click confirmation and "
          f"{t['error_among_prefilled']['k']} of them are wrong ({pct(t['error_among_prefilled'])}). That is {t['per_100_notes_prefilled_correctly']} of every 100 notes "
          f"pre-filled correctly, against {b['prefilled']}/{b['notes']} with {b['wrong']} errors today. The other "
          f"{t['needs_editing']['k']} notes need editing. A person confirms every note either way."
          + (f" Haiku-written test notes: {t['haiku_written']['prefilled']}/{t['haiku_written']['notes']} pre-filled, {t['haiku_written']['wrong_among_prefilled']} wrong among them." if t.get("haiku_written") else ""))
        corr = t["prefilled_and_correct"]["value"]
        err = t["error_among_prefilled"]["value"] or 0
        a(f"- Plan target for the cascade (at least 60% of notes pre-filled correctly, at most 5% error among them): "
          f"{'met' if corr >= 0.60 and err <= 0.05 else 'not met'} on test ({100 * corr:.1f}% and {100 * err:.1f}%).")
        s_ = ch.get("stress")
        alone = next((c for c in cas["configurations"] if c["gemma"] == ch["gemma"] and c["signal"] == "gemma_confidence_alone"), None)
        if s_ and alone and alone.get("stress"):
            sa = alone["stress"]
            a(f"- On the stress set (descriptive), the same rule pre-fills {s_['prefilled_for_one_click_confirmation']['k']}/{s_['notes']} notes with "
              f"{s_['error_among_prefilled']['k']} wrong; Gemma {ch['gemma']}'s own confidence alone, at its validation threshold, would pre-fill "
              f"{sa['prefilled_for_one_click_confirmation']['k']} with {sa['error_among_prefilled']['k']} wrong."
              + (" Agreement with a second reader keeps the error low when the phrasing shifts; confidence alone does not."
                 if (s_['error_among_prefilled']['value'] or 0) < (sa['error_among_prefilled']['value'] or 0) else ""))
    a("")
    # checks
    a("## Checked before scoring")
    a("")
    v = doc["verify"]
    for k, x in v.items():
        if k in ("all_ok", "adapters"):
            continue
        a(f"- `{k}`: {x['now'][:16]}... {'matches' if x['ok'] else 'DIFFERS FROM'} the recorded value.")
    for arm, x in v["adapters"].items():
        a(f"- adapter `{arm}`: {(x['now'] or 'missing')[:16]}... {'matches' if x['ok'] else 'DIFFERS FROM'} `data/scribe/v4/mlx/adapters-v1.json`.")
    pg = doc["preregistration"]
    a(f"- Preregistration: frozen_utc {pg['frozen_utc']}, file last modified {pg['file_mtime_utc']}; {pg['hash_note']}.")
    a("")
    # systems
    a("## Systems")
    a("")
    for s in ORDER:
        a(f"- **{NAMES[s]}**: {doc['systems'][s]}.")
    a("")
    # main table
    a("## Exact match (note level, Wilson 95% interval)")
    a("")
    a("Exact match means the entry route and every event (type, date, precision) equal the answer key after the system's own date code. "
      "A parse failure counts as wrong. Validation is the selection evidence from step 3, recomputed; test was read once here but had been read "
      "in earlier work, so it is post hoc; the stress set is the primary, frozen set, read once.")
    a("")
    a("| System | Validation (310) | Test (700) | Stress (308) | Stress held-out | Stress standard |")
    a("|---|---|---|---|---|---|")
    for s in ORDER:
        vv, tt, ss = sysd(doc, "val", s), sysd(doc, "test", s), sysd(doc, "stress", s)
        a(f"| {NAMES[s]} | {pct(vv['exact_match']) if vv else 'not run'} | {pct(tt['exact_match']) if tt else 'not run'} | "
          f"{pct(ss['exact_match']) if ss else 'not run'} | {pct(ss['slices']['heldout']) if ss else ''} | {pct(ss['slices']['standard']) if ss else ''} |")
    a("")
    for split in ("val", "test", "stress"):
        miss = doc["sets"][split]["not_scored"]
        if miss:
            a(f"- Not scored on {split}: " + "; ".join(f"{k}: {v}" for k, v in miss.items()) + ".")
    a("")
    # comparisons
    a("## Paired comparisons (exact McNemar, two-sided)")
    a("")
    a("Only B against A' on the stress held-out slice is the preregistered test. Every other line is descriptive.")
    a("")
    for key, title in (("stress_heldout", "Stress, held-out slice"), ("stress_standard", "Stress, standard slice"),
                       ("stress", "Stress, all notes"), ("test", "Test (700)"), ("val", "Validation (310)")):
        cs = doc["comparisons"].get(key) or []
        if not cs:
            continue
        a(f"**{title}**")
        a("")
        for c in cs:
            a(f"- {cmp_line(c)}")
        a("")
    aa = [c for k, cs in doc["comparisons"].items() for c in cs if c["a"] == "A" and c["b"] == "A'"]
    if aa and all(c["a_only_correct"] == 0 and c["b_only_correct"] == 0 for c in aa):
        a("A and A' give the same answer on every note of every set: no validation, test or stress note contains a phrase that only the "
          "lexicon resolves (the stress phrasings were held out of it on purpose). They differ only in what A' sends to a person.")
        a("")
    # stress slices
    a("## Stress set by slice")
    a("")
    present = [s for s in ORDER if s in st]
    a("| Slice | " + " | ".join(NAMES[s] for s in present) + " |")
    a("|---|" + "---|" * len(present))
    for name in ("heldout", "standard", "vague", "no_event", "no_event_with_heldout_distractor"):
        a(f"| {name} | " + " | ".join(short(st[s]['slices'][name]) for s in present) + " |")
    for name in st[present[0]]["by_curriculum"]:
        a(f"| curriculum: {name} | " + " | ".join(short(st[s]['by_curriculum'][name]) for s in present) + " |")
    for name in st[present[0]]["heldout_slice_by_family"]:
        a(f"| held-out family: {name} | " + " | ".join(short(st[s]['heldout_slice_by_family'][name]) for s in present) + " |")
    a("")
    # vague
    a("## Vague phrases: does a system invent a precise date?")
    a("")
    a("Each vague fact ('pari viikkoa sitten', 'viime kuussa' and similar) has no single correct day; the correct outcome is to send it to a person. "
      "A' flags a phrase when its frozen rule lists it for a person. The Nemotron reader flags a whole note when its validator still finds a problem "
      "after the repair, which is not specific to the vague phrase. A, B and C have no flag of their own. Note-level exact match counts any "
      "output event for the vague fact as wrong (the answer key holds precise events only), so for these notes read this table, not the exact-match row.")
    a("")
    a("| System | facts | sent to a person | precise date invented | month, no flag | dropped | parse failed | rest of the note exact |")
    a("|---|---|---|---|---|---|---|---|")
    for s in present:
        x = st[s]["vague_outcome"]
        a(f"| {NAMES[s]} | {x['facts']} | {short(x['sent_to_person'])} | {short(x['invented_precise_date'])} | {short(x['month_without_flag'])} | "
          f"{short(x['dropped'])} | {short(x['parse_failed'])} | {short(x['precise_part_exact'])} |")
    a("")
    # errors in days
    a("## Errors in days")
    a("")
    a("Per gold event whose type the system also output: the absolute difference between the predicted and the true date (nearest predicted date "
      "of that type). Per pathway interval: consecutive true events whose two types were both output; the error is the difference between the "
      "predicted and the true interval length. Missing types are counted separately.")
    a("")
    a("| Set | System | events (type missing) | event date: mean / median / p90 days, exact | interval: n, mean / median / p90 days, exact |")
    a("|---|---|---|---|---|")
    for split in ("test", "stress"):
        for s in ORDER:
            x = sysd(doc, split, s)
            if not x:
                continue
            e, i = x["errors_in_days"]["event_date_error"], x["errors_in_days"]["pathway_interval_error"]
            if not e.get("n"):
                continue
            a(f"| {split} | {NAMES[s]} | {x['errors_in_days']['gold_events']} ({x['errors_in_days']['type_missing']}) | "
              f"{e['mean_days']} / {e['median_days']} / {e['p90_days']}, {short(e['exact_0_days'])} | "
              f"{i.get('n', 0)}, {i.get('mean_days', 'n/a')} / {i.get('median_days', 'n/a')} / {i.get('p90_days', 'n/a')}, {short(i.get('exact_0_days'))} |")
    a("")
    # writer and date form
    a("## By writer and by date form")
    a("")
    a("Test notes were written by Nemotron (500) and Claude Haiku (200); the Haiku-written slice is the more honest one, because the students "
      "trained mostly on Nemotron-written notes. All stress notes were written by Nemotron.")
    a("")
    for split in ("val", "test"):
        a(f"**{ 'Validation' if split == 'val' else 'Test'} by writer**")
        a("")
        for s in ORDER:
            x = sysd(doc, split, s)
            if x:
                a(f"- {NAMES[s]}: " + "; ".join(f"{w} {short(r)}" for w, r in x["by_writer"].items())
                  + f"; with a relative date {short(x['with_relative_date'])}; absolute dates only {short(x['absolute_dates_only'])}.")
        a("")
    for split in ("test", "stress"):
        key = "by_date_form (notes with at least one fact in that form; groups overlap)"
        forms = sorted({f for s in ORDER if sysd(doc, split, s) for f in sysd(doc, split, s)[key]})
        pres = [s for s in ORDER if sysd(doc, split, s)]
        a(f"**{split.capitalize()} by date form** (a note counts in every form it contains)")
        a("")
        a("| Date form | " + " | ".join(NAMES[s] for s in pres) + " |")
        a("|---|" + "---|" * len(pres))
        for f in forms:
            a(f"| {f} | " + " | ".join(short(sysd(doc, split, s)[key].get(f)) for s in pres) + " |")
        a("")
    # parse failures
    a("## Parse failures")
    a("")
    for split in ("val", "test", "stress"):
        a(f"- {split}: " + "; ".join(f"{NAMES[s]} {short(sysd(doc, split, s)['parse_failures'])}" for s in ORDER if sysd(doc, split, s)) + ".")
    a("")
    # cascade
    if cas:
        a("## Cascade recalibration (validation only)")
        a("")
        a(f"Rule: {cas['rule']} Thresholds: {cas['selection_rule']}. Leak guard: {cas['leak_guard']}. Gemma answers: {cas['gemma_answers']}. "
          f"Error target {cas['alpha_pct']}% on validation, at least {cas['min_accepted']} accepted notes.")
        a("")
        a(f"Today's baseline: {cas['baseline_today']['prefilled']}/{cas['baseline_today']['notes']} with {cas['baseline_today']['wrong']} errors ({cas['baseline_today']['source']}).")
        a("")
        a("| Gemma | Signal | Validation: pre-filled, wrong | Test: pre-filled, wrong, correct per 100 | Test Haiku-written: pre-filled, wrong | Stress: pre-filled, wrong |")
        a("|---|---|---|---|---|---|")
        for c in cas["configurations"]:
            val = c["validation"]
            vt = f"{val['accepted']}/{val['n']}, {val['wrong']}" if val.get("threshold") is not None else "no feasible threshold"
            t = c.get("test")
            tt = (f"{t['prefilled_for_one_click_confirmation']['k']}/{t['notes']}, {t['error_among_prefilled']['k']}, {t['per_100_notes_prefilled_correctly']}"
                  if t else "n/a")
            hw = t.get("haiku_written") if t else None
            ht = f"{hw['prefilled']}/{hw['notes']}, {hw['wrong_among_prefilled']}" if hw else "n/a"
            s = c.get("stress")
            stt = f"{s['prefilled_for_one_click_confirmation']['k']}/{s['notes']}, {s['error_among_prefilled']['k']}" if s else "n/a"
            mark = " (chosen)" if cas.get("chosen") == {"gemma": c["gemma"], "signal": c["signal"]} else ""
            a(f"| {c['gemma']}{mark} | {c['signal']} | {vt} | {tt} | {ht} | {stt} |")
        a("")
        a("'gemma_confidence_alone' is the step 3 cascade without Nemotron, for comparison; it is not a candidate under the agreement rule.")
        a("")
        gated = [c for c in cas["configurations"] if c["signal"] != "gemma_confidence_alone" and c["validation"].get("threshold") is not None]
        if gated and all(c["validation"]["wrong"] == 0 for c in gated):
            a("On validation no agreed note was wrong for any Gemma arm, so the 5% target never binds: every agreement-gated threshold accepts every "
              "agreed note, and an extra confidence threshold can only remove notes on test. The recalibration therefore reduces to the agreement rule itself.")
            a("")
        if cas.get("chosen"):
            ch = next(c for c in cas["configurations"] if c["gemma"] == cas["chosen"]["gemma"] and c["signal"] == cas["chosen"]["signal"])
            diffs = (ch.get("test") or {}).get("wrong_among_prefilled_differences") or []
            if diffs:
                a(f"Agreed but wrong on test ({len(diffs)} notes, chosen configuration):")
                a("")
                for d in diffs:
                    a(f"- {d['writer']}-written note {d['id']}...: missing {', '.join(d['missing']) or 'nothing'}; extra {', '.join(d['extra']) or 'nothing'}"
                      + ("; route wrong" if d["route_wrong"] else "") + ".")
                a("")
    # engine
    par = doc.get("engine_parity_on_validation")
    if par:
        a("## Inference engine")
        a("")
        a("Single-sequence MLX decoding ran several times slower than in step 3, under GPU contention from another project's job "
          "(speeds in `runs/laneA-step3.jsonl` and `runs/laneA-step8.jsonl`), too slow to finish. Test and stress outputs therefore come from batched greedy decoding (`scribe/v4/binfer.py`, mlx_lm BatchGenerator) "
          "with the same model, adapter, prompt, stop tokens and token limit. Before any test or stress output was read, the batched engine re-ran "
          "the 310 validation notes:")
        a("")
        for arm, x in par.items():
            a(f"- {arm}: same resolved prediction on {x['same_resolved_prediction']}/{x['notes']} notes, same raw text on {x['same_raw_text']}/{x['notes']}; "
              f"exact {x['exact_single']} single vs {x['exact_batch']} batched.")
        eng = st.get("A", {}).get("engine", {})
        if len(eng) > 1:
            a(f"- Arm A's stress outputs mix engines ({', '.join(f'{k}: {v}' for k, v in eng.items())}): the single-sequence run was stopped for speed, "
              "no score had been read, and the remaining notes were generated batched, so no stress note was generated twice.")
        a("")
    a("## Limits")
    a("")
    a("- SYNTHETIC notes from two writer models; the stress notes all come from Nemotron, which also wrote most training notes, so only the phrasing is new, not the writing style.")
    a("- The Nemotron reader wrote the stress notes it reads here, so its stress score is optimistic.")
    a("- The test set had been read in earlier work; its numbers are post hoc. Validation selected the arms; the stress set is the only fresh, frozen set.")
    a("- The cascade thresholds rest on 310 validation notes; with a 5% target, one error moves the observed rate by about 0.3 points at full coverage.")
    a("- Finnish only. No Swedish slice was built.")
    a("- Interval error uses the nearest predicted date of each type, which is optimistic when a system outputs the same type twice.")
    a("")
    return "\n".join(L) + "\n"
