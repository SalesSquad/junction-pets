import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadPackages,collectionDigest} from '../lib/catalog.mjs';
import {makerCandidate} from '../lib/export.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const bindingPath=process.argv[2];
if(!bindingPath)throw new Error('Usage: npm run prepare:import -- <verified-host-bindings.json>. This prepares immutable candidates only.');
const bindings=JSON.parse(await readFile(resolve(bindingPath),'utf8')),packs=await loadPackages(root);
const candidates=packs.map(pack=>makerCandidate(pack,bindings));
const out=resolve(root,'dist/import-candidates');await mkdir(out,{recursive:true});
for(const candidate of candidates)await writeFile(resolve(out,candidate.makerRequest.slug+'.json'),JSON.stringify(candidate,null,2)+'\n');
await writeFile(resolve(out,'index.json'),JSON.stringify({schemaVersion:1,status:'prepared-not-submitted',contentSha256:collectionDigest(packs),items:candidates.map(c=>({petId:c.petId,file:c.makerRequest.slug+'.json',artifactSha256:c.artifactSha256}))},null,2)+'\n');
console.log(JSON.stringify({prepared:candidates.length,submitted:0,published:0,path:out}));
