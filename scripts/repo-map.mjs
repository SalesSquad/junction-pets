import {access, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {agentCatalog, checkSolutions} from './solution-workspace.mjs';
import {loadBrowserApps} from '../lib/browser-apps.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const pets=(await agentCatalog(root)).sort((a,b)=>a.company.slug.localeCompare(b.company.slug));
const solutions=await checkSolutions(root), apps=await loadBrowserApps(root);
const link=(label,path)=>`[${label.replaceAll('|','\\|')}](../${path})`;
const rows=[];
for(const pet of pets) {
  const slug=pet.company.slug, plugin=`plugins/${pet.slug}/`;
  await access(join(root,plugin));
  const products=solutions.filter(solution=>solution.agentIds.includes(pet.id));
  const slices=apps.filter(app=>app.petSlug===pet.slug);
  rows.push(`| ${link(pet.company.name,`pets/${slug}/`)} | ${link('Skills',plugin)} | ${products.map(solution=>link(solution.id,`solutions/${solution.id}/README.md`)).join(', ') || '—'} | ${slices.map(app=>link(app.name,`${app.source??`solutions/${app.solution}`}/${app.entry}`)).join(', ') || 'No bundled browser app'} |`);
}
const text=`# Repository map

Generated by \`node scripts/repo-map.mjs --write\` from pet manifests, solution manifests and \`apps/companion-browser-apps/catalog.json\`. Do not edit the table by hand. Check it with \`node scripts/repo-map.mjs --check\` after changing these associations.

${pets.length} pets, ${pets.length} plugin directories, ${solutions.length} solution workspaces and ${apps.length} bundled browser apps. These are source counts, not deployment or runtime qualification.

| Directory | Canonical purpose |
| --- | --- |
| [pets](../pets/) | Company identity, instructions, research and authored eval cases |
| [plugins](../plugins/) | Generated skills-only exports; regenerate through the plugin producer |
| [solutions](../solutions/) | Product-specific implementation, fixtures and handoff |
| [services](../services/) | Shared implementations and their own runtime contracts |
| [apps/catalog](../apps/catalog/) | Pet discovery UI, including each pet's bundled app links |
| [apps/companion-browser-apps](../apps/companion-browser-apps/README.md) | Explicit browser file allowlists and export adaptations |
| [apps/knowledge-os](../apps/knowledge-os/README.md) | Separate source-metadata shell; private API requires host authorization |
| [apps/meta-lens-apple](../apps/meta-lens-apple/) | Apple-native source; device qualification stays separate |
| [ops](../ops/AGENTS.md) | Developer coordination; private operational data belongs on the private host |

## Pet, solution and app associations

App links below open their **source entry files**. Run \`npm run dev\` to browse a pet and launch its exported browser demos. Server-backed and native products without a browser bundle retain their original README/run commands. A solution may reuse several pets; an app is attached to its selected launch pet. Banker and Lumo both belong to S-Pankki; product names do not add pets to the 34-company roster.

| Pet source | Plugin | Solution workspaces | Browser app source entries |
| --- | --- | --- | --- |
${rows.join('\n')}

## Latest work and integration

This map follows the checked-out source, not live GitHub status. Before declaring all work integrated, inspect [current PRs](https://github.com/SalesSquad/junction-pets/pulls), remote task branches and local dirty/unpushed work. A squash-merged task branch may have a different commit ID while its content is already on main. Preserve unmerged work and compare the actual changed files. Portfolio PR Recovery remains the sole existing PR integrator; this map starts no workers or deployments.
`;
const dest=join(root,'docs/REPOSITORY_MAP.md');
if(process.argv[2]==='--write') await writeFile(dest,text);
else if(process.argv[2]==='--check') {
  if(await readFile(dest,'utf8')!==text) throw new Error('Repository map is stale; run node scripts/repo-map.mjs --write');
  console.log(`Repository map matches ${pets.length} pets, ${solutions.length} solutions, ${apps.length} browser apps`);
} else process.stdout.write(text);
